"""Build deterministic, local CSS bundles; edit component sources, not outputs.

The legacy theme provides structural defaults. natural.css owns publication
type, spacing and colour tokens; natural-landing.css owns the landing layout.
Keep this order explicit so both GitHub Pages and VPS builds use the same CSS.
"""
from pathlib import Path

BASE = ('theme/nalar-hakim/style.css', 'preview/identity.css')
PUBLICATION = BASE + tuple('preview/' + name + '.css' for name in (
    'preview', 'editorial', 'redaksi', 'motion', 'natural', 'donation-networks', 'icons', 'editorial-motion', 'article-editorial', 'article-transitions', 'cubist-editorial'))
LANDING = BASE + tuple('preview/' + name + '.css' for name in (
    'landing', 'motion', 'natural', 'nature-scene', 'natural-landing',
    'butterfly', 'scroll-story', 'idea-flow', 'icons', 'editorial-motion', 'article-transitions', 'cubist-editorial'))


def build_styles(root: Path):
    for filename, sources in (('publication.css', PUBLICATION), ('landing-bundle.css', LANDING)):
        # All URL-bearing component sources are in preview/, as are outputs.
        # SVG fragment URLs and preview/fonts relative URLs keep their meaning.
        chunks = ['/* Generated by scripts/styles.py. Do not edit this bundle. */\n']
        for source in sources:
            chunks.append(f'\n/* Source: {source} */\n')
            chunks.append((root / source).read_text(encoding='utf-8').rstrip() + '\n')
        (root / 'preview' / filename).write_text(''.join(chunks), encoding='utf-8')
